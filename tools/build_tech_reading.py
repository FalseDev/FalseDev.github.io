#!/usr/bin/env python3
"""Generate the Tech Reading page from blogs-read-tech.json.

blogs-read-tech.json is git-ignored (it is your browsing history). What gets
committed is only what the page itself shows: tech-reading.md,
tech-reading-tags.md and assets/blogs.json (url -> tags, site, date).

    python3 tools/build_tech_reading.py
"""
import hashlib
import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "blogs-read-tech.json"
TAG_INDEX = "tech-reading-tags"

data = json.loads(SRC.read_text())
posts = list(data["posts"])
posts.sort(key=lambda p: (p["date"], p["site"], p["title"]), reverse=True)  # newest first

# ---------------- payload for the filter / ordering layer ----------------
payload = {p["url"]: {"t": p["tags"], "s": p["site"], "dt": p["date"]} for p in posts}
(REPO / "assets" / "blogs.json").parent.mkdir(parents=True, exist_ok=True)
(REPO / "assets" / "blogs.json").write_text(json.dumps(payload, ensure_ascii=False, indent=1) + "\n")

# ---------------- the page ----------------
def esc(text):
    return text.replace("[", "\\[").replace("]", "\\]")


body = ["---", "title: Tech Reading", "meta: assets/blogs.json", "order: chrono,site", "group: site", "---", ""]
sites = {}
for p in posts:
    sites.setdefault(p["site"], 0)
    sites[p["site"]] += 1
tags = {}
for p in posts:
    for t in p["tags"]:
        tags[t] = tags.get(t, 0) + 1

body.append(f"{len(posts)} technical posts, {len(sites)} sites, {min(p['date'] for p in posts)} to "
            f"{max(p['date'] for p in posts)}. Filter by tag, or switch the order between newest "
            f"first and grouped by site. Without JavaScript: [{TAG_INDEX.replace('-', ' ').title()}]({TAG_INDEX}.md).")
body.append("")
body.append("# Posts")
body.append("")
for p in posts:
    # the dash lives inside the span so hiding the site (grouped view) leaves "title · date"
    body.append(f"- [{esc(p['title'])}]({p['url']}) <span class=\"site\">— {p['site']}</span> · {p['date']}")
body += ["", "---", "", "← [Home](index.md) · [My Resources](my-resources.md) · "
         f"[Tag index]({TAG_INDEX}.md)", ""]
(REPO / "tech-reading.md").write_text("\n".join(body) + "\n")

# ---------------- tag index: plain links, no JavaScript needed ----------------
idx = ["---", "title: Tech Reading — Tag Index", "---", ""]
idx.append(f"Every tag on [Tech Reading](tech-reading.md) with the posts under it. {len(tags)} tags.")
idx.append("")
for t in sorted(tags, key=lambda x: (-tags[x], x)):
    idx.append(f"## {t} ({tags[t]})")
    idx.append("")
    for p in sorted((p for p in posts if t in p["tags"]), key=lambda p: p["date"], reverse=True):
        idx.append(f"- [{esc(p['title'])}]({p['url']}) — {p['site']} · {p['date']}")
    idx.append("")
idx += ["---", "", f"← [Tech Reading](tech-reading.md) · [Home](index.md)", ""]
(REPO / f"{TAG_INDEX}.md").write_text("\n".join(idx) + "\n")

# ---------------- head include (Jekyll's hook for the slate theme) ----------------
def digest(rel):
    return hashlib.sha256((REPO / rel).read_bytes()).hexdigest()[:8]


def liq(rel):
    return "{{ '" + rel + "' | relative_url }}"


inc = ["{% comment %}Generated by tools/build_tech_reading.py. Loaded only on pages whose front matter sets `meta`;",
       "the ?v= values are content hashes, so an edited stylesheet or script is never served stale.{% endcomment %}",
       "{%- if page.meta %}",
       '<link rel="stylesheet" href="' + liq("/assets/css/tags.css") + "?v=" + digest("assets/css/tags.css") + '">',
       '<script src="' + liq("/assets/js/tags.js") + "?v=" + digest("assets/js/tags.js") + '" defer',
       '        data-meta="{{ page.meta }}"',
       '{% if page.order %} data-order="{{ page.order }}"{% endif %}',
       '{% if page.group %} data-group="{{ page.group }}"{% endif %}></script>',
       '<noscript><p class="tagnone">Filtering and ordering need JavaScript; the list below is complete without it.</p></noscript>',
       "{%- endif %}", ""]
(REPO / "_includes" / "head-custom.html").write_text("\n".join(inc))
print(f"tech-reading.md      {len(posts)} posts, {len(sites)} sites, {len(tags)} tags")
print(f"assets/blogs.json    {(REPO / 'assets/blogs.json').stat().st_size} bytes")
print(f"{TAG_INDEX}.md       {len(tags)} tag sections")
